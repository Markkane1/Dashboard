import { z } from "zod";

const courseSchema = z.object({
  id: z.string(),
  title: z.string(),
  category: z.enum([
    "biological-diversity",
    "chemicals-waste",
    "climate-atmosphere",
    "environmental-governance",
    "land-agriculture",
    "marine-freshwater",
  ]),
  sdgGoals: z.array(z.number()),
  topics: z.array(z.enum(["mea-introductory", "human-rights", "gender"])),
  mea: z.array(z.string()),
  syllabusUrl: z.string().optional(),
  courseUrl: z.string(),
  isDiploma: z.boolean(),
  isExternal: z.boolean(),
  externalUrl: z.string().optional(),
  description: z.string().optional(),
});

export function validateCourse(course: any): Course {
  return courseSchema.parse(course);
}

// Run runtime check on every course entry to prevent silent bad data bugs
courses.forEach((c) => {
  try {
    validateCourse(c);
  } catch (error) {
    throw new Error(
      `Course runtime validation failed for Course ID "${c.id}": ${
        error instanceof Error ? error.message : String(error)
      }`
    );
  }
});
